/**
 * Translates a dynamic string into simple, natural Tamil if language is 'ta'.
 * If no translation exists or language is 'en', returns original text.
 */
export function tr(text, lang = "en") {
  if (!text || lang !== "ta") return text;
  
  const trimmed = String(text).trim();
  
  // Exact match lookup
  if (contentDictionary[trimmed]) {
    return contentDictionary[trimmed];
  }
  
  // Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const [key, value] of Object.entries(contentDictionary)) {
    if (key.toLowerCase() === lower) {
      return value;
    }
  }

  // Prefix match for "Prepare ..."
  if (lower.startsWith("prepare ")) {
    const docName = trimmed.slice(8).trim();
    const translatedDoc = tr(docName, "ta");
    return `${translatedDoc} தயார் செய்யவும்`;
  }

  // Prefix match for "Keep ... ready"
  if (lower.startsWith("keep ") && lower.includes("ready")) {
    return `விண்ணப்பிக்க இந்த ஆவணத்தை கையில் தயாராக வைத்திருக்கவும்.`;
  }

  // Prefix match for "Provide ..."
  if (lower.startsWith("provide ")) {
    const fieldName = trimmed.slice(8).trim();
    return `உங்கள் ${fieldName} விவரங்களை உள்ளிடவும்`;
  }

  return text;
}
